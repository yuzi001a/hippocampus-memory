def test_good_yin_passes():
    v = e1._validate_yin_content(_good_yin())
    assert v["ok"] is True, v["reasons"]
    assert len(v["anchors"]) >= 6


def test_project_list_is_rejected():
    v = e1._validate_yin_content(_project_list_yin())
    assert v["ok"] is False
    joined = "; ".join(v["reasons"])
    assert ("项目清单味" in joined or "核心特质覆盖" in joined
            or "底色特质" in joined), joined


def test_short_yin_is_rejected():
    v = e1._validate_yin_content("## 我是谁\n- 一句话(来源: x)\n")
    assert v["ok"] is False
    assert any("过短" in r or "小节" in r for r in v["reasons"])


def test_missing_section_is_rejected():
    body = _good_yin().split("## 怎么判断")[0] + _good_yin().split("## 行为基线")[1]
    v = e1._validate_yin_content("## 行为基线" + body)
    assert v["ok"] is False
    assert any("缺少小节" in r or "只有" in r for r in v["reasons"])


def test_project_tokens_ignored_inside_source_marks():
    """来源标注里的项目名是溯源, 不算项目味。"""
    body = _good_yin().replace(
        "(来源: 多网络出口优化：热点实测与 leastPing)",
        "(来源: P0-B3 v4.0.3 H18R 多网络出口优化)")
    v = e1._validate_yin_content(body)
    assert v["ok"] is True, v["reasons"]
